-- Renumera semanas y listas para que arranquen en 1 (la primera semana figuraba como 2 y la primera lista como 002).
-- No borra nada: conserva propuestas, votos, reportes, escrutinio y participación; solo cambia los números.

-- 1) Las claves foráneas hacia semanas(n) y propuestas(id) pasan a propagar los cambios de número.
do $$
declare r record;
begin
  for r in
    select c.conrelid::regclass as tabla, c.conname, pg_get_constraintdef(c.oid) as def
    from pg_constraint c
    where c.contype = 'f'
      and c.confrelid in ('public.semanas'::regclass, 'public.propuestas'::regclass)
      and pg_get_constraintdef(c.oid) not like '%ON UPDATE CASCADE%'
  loop
    execute format('alter table %s drop constraint %I', r.tabla, r.conname);
    execute format('alter table %s add constraint %I %s on update cascade', r.tabla, r.conname, r.def);
  end loop;
end $$;

-- 2) Semanas: la más antigua pasa a ser la 1 (pasando por negativos para no chocar con la clave primaria).
update public.semanas set n = -(n - (select min(n) from public.semanas) + 1);
update public.semanas set n = -n;

-- 3) Listas: ids correlativos desde 1, en el mismo orden (el id es el "Lista N°").
alter table public.propuestas alter column id set generated by default;
update public.propuestas p set id = -r.nuevo
  from (select id, row_number() over (order by id) as nuevo from public.propuestas) r
  where p.id = r.id;
update public.propuestas set id = -id;
alter table public.propuestas alter column id set generated always;
select setval(pg_get_serial_sequence('public.propuestas', 'id'), coalesce((select max(id) from public.propuestas), 0) + 1, false);
